const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[^a-zа-я0-9+ ]/g, ' ');
// слова, без которых вопрос не меняется: «как сохранить видео» = «сохранить видео»
const STOP = new Set(['как', 'что', 'где', 'мне', 'меня', 'это', 'эту', 'этот', 'для', 'чтобы', 'можно', 'нужно', 'надо', 'хочу',
  'сделать', 'сделай', 'или', 'не', 'на', 'по', 'из', 'за', 'от', 'до', 'ли', 'же', 'бы', 'мой', 'мою', 'моё', 'мое', 'все', 'всё']);

/**
 * Поиск по справке. Слово ищется по началу (без окончания: «паузы» найдёт «паузу»).
 * Совпадение в заголовке важнее, чем в «как ещё ищут», а там — важнее, чем в тексте.
 * Статья подходит, если нашлась хотя бы половина слов: опечатка в одном слове не оставит без ответа.
 */
export function searchHelp(query: string, list: HelpArticle[] = HELP): HelpArticle[] {
  const all = norm(query).split(/\s+/).filter(w => w.length > 1);
  const words = all.filter(w => !STOP.has(w));
  if (!words.length) return list;
  const phrase = words.join(' ');
  const need = Math.max(1, Math.ceil(words.length / 2));
  const scored = list.map(a => {
    const title = norm(a.title), keys = norm(a.keywords), rest = norm(a.body.join(' ') + ' ' + a.group);
    let score = 0, hit = 0;
    for (const w of words) {
      const stem = w.length > 5 ? w.slice(0, w.length - 2) : w.length > 4 ? w.slice(0, -1) : w;
      const s = title.includes(stem) ? 3 : keys.includes(stem) ? 2 : rest.includes(stem) ? 1 : 0;
      if (s) { hit++; score += s; }
    }
    if (words.length > 1 && (keys.includes(phrase) || title.includes(phrase))) score += 4; // спросили теми же словами
    return { a, score, hit };
  });
  // если есть статьи, где нашлись все слова, показываем только их; иначе — где нашлась хотя бы половина
  const full = scored.some(x => x.hit === words.length);
  return scored.filter(x => (full ? x.hit === words.length : x.hit >= need)).sort((x, y) => y.hit - x.hit || y.score - x.score).map(x => x.a);
}
